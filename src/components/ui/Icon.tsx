import clsx from 'clsx'
import { createElement } from 'react'

import { iconFor } from '@/lib/icons'

export function Icon({ name, className }: { name?: string | null; className?: string }) {
  const icon = iconFor(name)
  return icon ? createElement(icon, { 'aria-hidden': true, className: clsx('size-6', className), strokeWidth: 1.75 }) : null
}

/** Icon in a soft rounded tile. */
export function IconTile({ name, dark = false, className }: { name?: string | null; dark?: boolean; className?: string }) {
  if (!iconFor(name)) return null
  return (
    <span
      className={clsx(
        'inline-flex size-12 shrink-0 items-center justify-center rounded-xl',
        dark ? 'bg-white/10 text-gold-400 ring-1 ring-white/15' : 'bg-plum-100 text-plum-800',
        className,
      )}
    >
      <Icon name={name} />
    </span>
  )
}

